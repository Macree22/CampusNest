<?php
if (!isset($_SESSION['user_id']) || $_SESSION['role'] !== 'student') {
    header("Location: index.php");
    exit;
}

$paymentID = $_GET['paymentID'] ?? null;
if (!$paymentID) {
    echo "<div class='p-8 text-center text-red-600'>No payment ID specified.</div>";
    exit;
}

// Query Payment, Student, and Listing details for the receipt
$stmt = $pdo->prepare("
    SELECT p.*, s.firstName, s.lastName, s.studentNumber, l.title, l.address, l.monthlyRent 
    FROM Payment p
    JOIN Student s ON p.studentID = s.studentID
    JOIN Listing l ON p.listingID = l.listingID
    WHERE p.paymentID = ? AND p.studentID = ?
");
$stmt->execute([$paymentID, $_SESSION['user_id']]);
$receipt = $stmt->fetch();

if (!$receipt) {
    echo "<div class='p-8 text-center text-red-600'>Receipt not found or unauthorized access.</div>";
    exit;
}
